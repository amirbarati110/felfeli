    public const FALLBACK = 'sayer';

    public static function classify(string $name): string
    {
        $name = str_replace(['ي', 'ك'], ['ی', 'ک'], $name);

        foreach (self::RULES as $slug => $keywords) {
            foreach ($keywords as $kw) {
                $needle = str_replace(['ي', 'ك'], ['ی', 'ک'], $kw);
                if (mb_stripos($name, $needle) !== false) {
                    return $slug;
                }
            }
        }

        return self::FALLBACK;
    }
